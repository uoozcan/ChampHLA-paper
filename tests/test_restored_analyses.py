"""The analyses restored from the earlier drafts must reconcile with the paper.

scripts/restored_analyses.py recomputes them from runtime_data/joined_development.tsv;
these tests pin the artifacts to that input and to the primary performance table,
and check that Supplementary S12 shows the artifact values.
"""
from __future__ import annotations

import csv
import hashlib
import json
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / "artifacts" / "restored_analyses"
PERFORMANCE = ROOT / "artifacts" / "development_corrected" / "method_performance.tsv"
SUPPLEMENT = ROOT / "manuscripts" / "benchmark" / "supplementary.md"
RERUN = ROOT / "provenance" / "development_rerun_v350"


def _rerun_inputs() -> bool:
    manifest = ROOT / "data" / "development" / "input_manifest.json"
    return json.loads(manifest.read_text(encoding="utf-8")).get(
        "schema_version") == "champhla-development-rerun-inputs-1"


def _performance() -> list[dict[str, str]]:
    """S12 is an analysis of the historical stored outputs. On v3.5.0 rerun inputs it is
    reconciled with the archived pre-rerun registry, not with the rerun's results."""
    if not _rerun_inputs():
        return _read(PERFORMANCE)
    return [
        {"modality": row["modality"], "method": row["method"],
         "genotypes_correct": row["correct"]}
        for row in _read(RERUN / "historical_result_registry_pre_v350.tsv")
        if row["result_id"].startswith("DEV_CORRECTED_") and row["correct"]
    ]


def _read(path: Path) -> list[dict[str, str]]:
    with path.open(encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle, delimiter="\t"))


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _consensus_correct() -> dict[str, int]:
    return {row["modality"]: int(row["genotypes_correct"]) for row in _performance()
            if row["method"] == "SimplePluralityLex"}


def test_manifest_matches_inputs_and_outputs():
    manifest = json.loads((ART / "manifest.json").read_text(encoding="utf-8"))
    joined = ROOT / manifest["inputs"]["joined_development"]["path"]
    input_manifest = ROOT / "data" / "development" / "input_manifest.json"
    if _rerun_inputs():
        # the historical joined table it was computed from is superseded by the rerun
        input_manifest = RERUN / "historical_inputs_pre_v350" / "input_manifest.json"
    elif not joined.is_file():
        pytest.skip("runtime_data/ is regenerated by scripts/run_local_verification.sh")
    else:
        assert _sha256(joined) == manifest["inputs"]["joined_development"]["sha256"]
    expected_source = json.loads(
        input_manifest.read_text(encoding="utf-8")
    )["source_sha256"]["caller_rows"]
    assert manifest["inputs"]["caller_source"]["sha256"] == expected_source
    for name, digest in manifest["outputs"].items():
        assert _sha256(ART / name) == digest, name


def test_disagreement_classes_partition_the_endpoint():
    rows = _read(ART / "discordance_taxonomy.tsv")
    for assay, correct in _consensus_correct().items():
        members = [row for row in rows if row["assay"] == assay]
        assert sum(int(row["loci"]) for row in members) == int(members[0]["assay_loci"])
        assert sum(int(row["consensus_correct"]) for row in members) == correct


def test_per_gene_totals_equal_the_performance_table():
    totals = {(row["assay"], row["method"]): int(row["correct"])
              for row in _read(ART / "per_gene_caller_concordance.tsv") if row["gene"] == "all"}
    for row in _performance():
        method = row["method"][len("Caller:"):] if row["method"].startswith("Caller:") else row["method"]
        method = "ChampHLA-Consensus" if method == "SimplePluralityLex" else method
        if (row["modality"], method) in totals:
            assert totals[(row["modality"], method)] == int(row["genotypes_correct"]), method


def test_cross_assay_strata_add_up():
    rows = {row["stratum"]: row for row in _read(ART / "cross_assay_agreement.tsv")}
    assert (int(rows["assays_agree"]["loci"]) + int(rows["assays_disagree"]["loci"])
            == int(rows["all"]["loci"]))
    assert sum(int(rows[f"gene_{g}"]["loci"]) for g in "ABC") == int(rows["all"]["loci"])


def test_supplement_s12_shows_the_artifact_values():
    section = SUPPLEMENT.read_text(encoding="utf-8").split("## S12.", 1)[1]
    for row in _read(ART / "per_gene_caller_concordance.tsv"):
        assert f"{row['correct']}/{row['loci']} ({row['concordance_percent']})" in section
    for row in _read(ART / "caller_calibration.tsv"):
        if row["scored_loci"] != "0":
            assert f"| {row['brier']} | {row['ece']} |" in section
